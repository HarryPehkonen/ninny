"""Adapters as config: turn a task's toolchain into Ninny's exit-code contract.

Ninny's loop never parses compiler output, and that is what makes it language-blind. The
price is paid in each task's adapter -- the script Ninny's `run_tests` action calls, which
has to answer the contract on behalf of a toolchain that does not speak it:

    0  the tests ran and passed
    1  the tests ran and failed          -- a RED observation
    2  nothing ran                       -- never a RED

Six of those adapters exist, hand-written, 41-72 lines each, 3-5 hand-rolled guards each --
and every defect of the 2026-10-23 campaign lived in that layer rather than in the harness:
`tasks/bits` refused the edit its own docs required, and `tasks/intset` reported a genuine
red as exit 2 because its guard matched Cargo's `error: test failed, to rerun pass ...` line.

So the adapter becomes a CONFIG: a `[runner]` table in the task's own `task.toml`, rendered
into the tree's `tools/run_own_tests.sh`. Rendered, not interpreted -- the script stays a real
file in the tree, because the tree's own files are what teaches an agent the rules (measured:
all three bits arms learned the register-your-test rule from the tree, without being told).
Nothing new runs inside the sandbox, no dependency is added, and the file is still what
`test_cmd` points at.

THE SCHEMA -- nine keys, and every one of them is needed by a task in this repo:

    about          one line naming the toolchain; rendered into the file's header
    note           the task's own prose, kept verbatim in the header: the traps a reader
                   (or an agent) needs and a schema cannot express
    require        a glob that must match at least one file, or nothing runs (exit 2) --
                   says WHY before paying for a build
    build          a detached build step; a non-zero exit is 2, never a red
    run            the test command (may be a loop over files, for the bash family)
    build_fail     a regex proving the suite did not compile: the case a toolchain hides
                   behind its ordinary "tests failed" exit code
    sum            a regex whose captured group is SUMMED (cases that ran)
    count          a regex whose MATCHES are counted
    count_minus    a regex whose MATCHES are SUBTRACTED (the `node --test` wart: a test
                   file with no cases is reported as a case)
    rc_unrunnable  the exit code that means "could not run at all" when it is not the
                   toolchain's ordinary failure code

WHAT IS *NOT* IN THE SCHEMA, and why (each was in the first draft and fell out when the six
real adapters were written down): `failed`, `empty`, `ran` and `rc_fail`.
  * `empty` and `ran` collapse into one rule -- if the case count comes out zero, nothing was
    observed, whatever the exit code said. That is the anti-vacuous rule (a suite that
    asserted nothing is not a pass) and it is what `unittest`'s `Ran 0 tests`, ctest's
    "No tests were found" and the frozen C++ harness's "0 checked, 0 failed" all have in
    common.
  * `failed` is unnecessary because every one of the six toolchains exits non-zero when a
    case fails -- and the count already had to be parsed, so the failure signal is free.
  * `rc_fail` is unnecessary for the same reason: ctest's 8 is already non-zero.
A key earns its place by a task that needs it; there is no seventh key waiting for a reason.

THE REPLAY SEAM, which is why this is testable without running a compiler: a rendered script
honours `NINNY_RUNNER_REPLAY` (a file holding a recorded transcript) and
`NINNY_RUNNER_REPLAY_RC`. With those set it skips `require`/`build`/`run` and classifies the
recording instead, so `tests/fixtures/runners/` exercises the very thing that runs in a
sandbox, rather than a Python mirror of it that could drift.
"""

from __future__ import annotations

import re
import shlex
from pathlib import Path

HEADER = """#!/usr/bin/env bash
# {about}
#
# Rendered from the [runner] table in task.toml by `ninny runner --write`. Do not edit this file
# by hand: `ninny runner --check` fails when it differs from its config, and the gate runs that.
#
# The exit code is the contract the harness reads, so each code means exactly one thing:
#   0  the tests ran and passed
#   1  the tests ran and failed          -- a RED observation
#   2  nothing ran                       -- nothing was observed, so not a RED either
#
# A build error, an empty suite and a suite that asserts nothing are all 2: none of them
# observed a failing test. tools/ is not the agent's to edit.
{note}set -uo pipefail
here=$(cd "$(dirname "$0")" && pwd)

if [ -n "${{NINNY_RUNNER_REPLAY:-}}" ]; then
  # A recorded transcript, so the corpus can test this script without a toolchain. Read it
  # BEFORE moving into the tree, so the path stays the caller's to give -- relative or absolute.
  out=$(cat "$NINNY_RUNNER_REPLAY" 2>&1)
  rc=${{NINNY_RUNNER_REPLAY_RC:-0}}
else
  cd "$here/.." || exit 2
{steps}fi

# --- the verdict, in one order, for every toolchain
out_and_rc_done=1
"""

COUNT_SUM = """{var}=$(printf '%s\\n' "$out" | grep -oE {pat} | sed -E {sub} | awk '{{t += $1}} END {{print t + 0}}')
"""

COUNT_PLAIN = """{var}=$(printf '%s\\n' "$out" | grep -cE {pat})
"""


def _as_list(value) -> list[str]:
    """One pattern or a list of them; absent means the key is not used."""
    if value is None:
        return []
    if isinstance(value, str):
        return [value]
    return [str(v) for v in value]


def _q(pattern: str) -> str:
    """A shell single-quoted literal. Patterns are regexes; a quote in one is an author error."""
    if "'" in pattern:
        raise ValueError(f"a runner pattern may not contain a single quote: {pattern!r}")
    return "'" + pattern + "'"


def _glob(pattern: str) -> str:
    """A shell glob that still globs: quote the directory, leave the pattern to expand."""
    head, slash, tail = pattern.rpartition("/")
    if not slash:
        return pattern
    return f"{shlex.quote(head)}/{tail}" if head else f"/{tail}"


def _grep(pattern: str, *, quiet: bool = True) -> str:
    flag = "-qE" if quiet else "-cE"
    return f'printf \'%s\\n\' "$out" | grep {flag} {_q(pattern)}'


def _group_from(pattern: str) -> str:
    """The sed expression that turns a match into its captured group."""
    if "(" not in pattern:
        raise ValueError(
            f"`sum` needs a captured group to add up, and {pattern!r} has none. "
            "Use `count` if the number of matches is the count."
        )
    return "'" + "s/" + pattern + "/\\1/" + "'"


def render(config: dict) -> str:
    """The adapter script for one `[runner]` table. Deterministic: same config, same bytes."""
    about = str(config.get("about") or "the task's own test command, as its toolchain reports it")
    note = str(config.get("note") or "")
    note_block = "".join(f"# {line}\n" if line.strip() else "#\n" for line in note.splitlines())
    if note_block:
        note_block += "#\n"

    require = _as_list(config.get("require"))
    build = config.get("build")
    run = config.get("run")
    build_fail = _as_list(config.get("build_fail"))
    sums = _as_list(config.get("sum"))
    counts = _as_list(config.get("count"))
    minus = _as_list(config.get("count_minus"))
    unrunnable = config.get("rc_unrunnable")

    if not run:
        raise ValueError("a [runner] table needs `run`: the command that runs the tests")

    # --- the part that runs, skipped entirely in replay mode
    steps = ""
    if require:
        globs = " ".join(_glob(g) for g in require)
        steps += (
            f"  if ! ls {globs} >/dev/null 2>&1; then\n"
            f'    echo "nothing to run yet: no {require[0]} -- write one case that fails because\n'
            f'           the behaviour is not there, then run this again."\n'
            f'    echo "NINNY_TESTS: 0"\n'
            f"    exit 2\n  fi\n"
        )
    if build:
        steps += (
            f'  {build} > build.log 2>&1\n'
            f"  if [ $? -ne 0 ]; then\n"
            f'    echo "BUILD FAILED -- nothing was built and nothing ran, so this is exit 2."\n'
            f"    tail -20 build.log\n"
            f'    echo "NINNY_TESTS: 0"\n'
            f"    exit 2\n  fi\n"
        )
    steps += f'  out=$({run} 2>&1)\n  rc=$?\n'

    # --- the verdict and the count
    counting = ""
    terms = []
    for i, pattern in enumerate(sums):
        var = f"n{i}"
        counting += COUNT_SUM.format(var=var, pat=_q(pattern), sub=_group_from(pattern))
        terms.append(var)
    for j, pattern in enumerate(counts):
        var = f"c{j}"
        counting += COUNT_PLAIN.format(var=var, pat=_q(pattern))
        terms.append(var)
    for k, pattern in enumerate(minus):
        var = f"m{k}"
        counting += COUNT_PLAIN.format(var=var, pat=_q(pattern))
        terms.append(f"-{var}")
    if not terms:
        raise ValueError("a [runner] table needs `sum` or `count`: the case count is the evidence")
    joined_terms = " + ".join(terms)
    counting += f"\ncount=$(( 0 + {joined_terms} ))\n"

    rules = ""
    if build_fail:
        joined = "|".join(build_fail)
        rules += (
            f"if {_grep(joined)}; then\n"
            f'  echo "BUILD FAILED -- the suite did not compile, so nothing ran. A build error is"\n'
            f'  echo "not a RED, and exit code 2 is how this script says so."\n'
            f'  echo "NINNY_TESTS: 0"\n'
            f"  exit 2\nfi\n\n"
        )
    if unrunnable is not None:
        rules += (
            f'if [ "$rc" -eq {int(unrunnable)} ]; then\n'
            f'  echo "a test script could not run at all -- what it meant to check was not observed"\n'
            f'  echo "NINNY_TESTS: 0"\n'
            f"  exit 2\nfi\n\n"
        )
    rules += counting + (
        '\n# The count is evidence even when it is zero: the record needs to know whether a run\n'
        '# collected nothing or failed on something, so it is always printed.\n'
        + 'echo "NINNY_TESTS: $count"\n\n'
    )
    rules += (
        '# Zero cases means nothing was observed -- a build that succeeds is not a suite that\n'
        '# asserts, and a suite that collects nothing is not a red. Same rule, every toolchain.\n'
        + 'if [ "$count" -eq 0 ]; then\n'
        + '  echo "no test cases ran at all -- nothing was observed, so this is exit 2 and not a RED"\n'
        + "  exit 2\nfi\n\n"
        + 'if [ "$rc" -ne 0 ]; then\n  exit 1\nfi\nexit 0\n'
    )

    script = HEADER.format(about=about, note=note_block, steps=steps)
    script = script.replace("out_and_rc_done=1\n", rules)
    return script


def task_check_cmd(task) -> str | None:
    """The declared cheap check for this task, or None when nothing is declared.

    A cheap check is not a smaller suite: it is the step that has to work before the suite can mean
    anything -- a build, a compile, a parse. Measured on a 126-translation-unit repository, an
    incremental build after one source write costs 4 s against 120 s for the acceptance command, and
    the preflight had already paid to warm the build directory before the arm's first step. The
    signal was sitting there unread, for every edit the arm made.

    Declared, never inferred: a task says `[runner] build`, a repository run says `--check-cmd`. A
    toolchain with no such step declares nothing, and that absence is honest rather than faked.
    """
    explicit = getattr(task, "check_cmd", None)
    if explicit:
        return explicit
    return (config_for(task.meta) or {}).get("build")


def config_for(task_meta: dict) -> dict | None:
    """The `[runner]` table of a loaded task, or None when the task brings its own script."""
    table = task_meta.get("runner")
    if table is None:
        return None
    if not isinstance(table, dict):
        raise ValueError("[runner] must be a table in task.toml")
    return table


def rendered_path(task_root: Path, task_meta: dict) -> Path:
    """Where a task's rendered adapter belongs: beside every other frozen file, in the tree."""
    return task_root / str(task_meta.get("tree") or "tree") / "tools" / "run_own_tests.sh"


def rendered_paths(task_root: Path, task_meta: dict) -> list[Path]:
    """Every copy of the instrument: the tree the agent edits, and the answer key.

    The answer key is a solved copy of the SAME tree, so it carries the same runner -- and for
    a task whose oracle freezes the runner, a fixed/ copy left behind is a hash mismatch that
    reads as "the task is unsolvable". Rendering both is how that stops happening.
    """
    paths = [rendered_path(task_root, task_meta)]
    fixed = task_meta.get("fixed_tree")
    if fixed:
        candidate = task_root / str(fixed) / "tools" / "run_own_tests.sh"
        if candidate.exists():
            paths.append(candidate)
    return paths


def drift(task_root: Path, task_meta: dict) -> tuple[bool, str]:
    """Is the file on disk what the config renders? The gate asks this."""
    config = config_for(task_meta)
    if config is None:
        return True, "no [runner] table: this task brings its own adapter"
    want = render(config)
    for target in rendered_paths(task_root, task_meta):
        if not target.exists():
            return False, f"{target} does not exist"
        if want != target.read_text():
            return False, f"{target} differs from the [runner] table in task.toml"
    return True, "the adapter on disk is what the config renders"